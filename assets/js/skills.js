/* Skills browser — loads skills-index.json, groups by category, live filter.
   Rotation 20 (Skills Usefulness Audit): every card carries the skill's
   plain-language "what this gets you" line (index field gets_you), and
   reference skills (audience === "reference" — agent/meta procedures and
   skills for models nobody can use yet) render in their own group at the
   end, marked, instead of posing as beginner skills.
   Rotation 20 completion (VP-0010): every card LINKS to the skill's own
   in-site page (skills/<id>.html, generated by build_site.py's
   build_skill_pages from the skill files) — title link plus an explicit
   "Open the skill" link. Zero dead-end cards. */
(function () {
  "use strict";

  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  var els = {
    filter: document.getElementById("skills-filter"),
    count: document.getElementById("skills-count"),
    list: document.getElementById("skills-list"),
    empty: document.getElementById("skills-empty")
  };
  if (!els.list) return;

  var all = [];
  var CAT_NAMES = {
    prompts: "Prompt templates", camera: "Camera moves", models: "Directing models",
    checklists: "Checklists & audits", longform: "Long-form pipeline", techniques: "Winning techniques",
    craft: "Craft techniques", entry: "Competition entry", workflow: "Workflow",
    compare: "Model comparisons", fix: "Fix-it guides", budget: "Budgeting",
    delivery: "Delivery", audio: "Audio", recipes: "Shoot recipes",
    styles: "Style guides", performance: "Directing performance", grading: "Color grading",
    distribution: "Distribution", legal: "Rights & disclosure",
    episodes: "Episodes & series", studio: "Studio planners"
  };

  function catOf(path) { return path.split("/")[1]; }

  function card(s) {
    var href = "skills/" + encodeURIComponent(s.id) + ".html";
    return '<article class="card skill-card">' +
      '<h3><a href="' + href + '">' + esc(s.title) + "</a></h3>" +
      (s.gets_you ? '<p class="skill-gets"><strong>Gets you:</strong> ' + esc(s.gets_you) + "</p>" : "") +
      "<p>" + esc(s.description) + "</p>" +
      '<p class="skill-id"><code>' + esc(s.id) + "</code></p>" +
      '<p class="skill-open"><a href="' + href + '">Open the skill &rarr;</a></p>' +
      "</article>";
  }

  function render(q) {
    q = (q || "").trim().toLowerCase();
    var shown = all.filter(function (s) {
      return !q || (s.title + " " + s.description + " " + (s.gets_you || "") + " " + s.id).toLowerCase().indexOf(q) !== -1;
    });
    var beginner = shown.filter(function (s) { return s.audience !== "reference"; });
    var reference = shown.filter(function (s) { return s.audience === "reference"; });
    var groups = {};
    beginner.forEach(function (s) {
      var c = catOf(s.path);
      (groups[c] = groups[c] || []).push(s);
    });
    var html = Object.keys(groups).sort().map(function (c) {
      var cards = groups[c].map(card).join("");
      return '<h3 class="section-h">' + esc(CAT_NAMES[c] || c) + ' <span class="count">(' + groups[c].length + ")</span></h3>" +
        '<div class="chapter-grid">' + cards + "</div>";
    }).join("");
    if (reference.length) {
      html += '<h3 class="section-h">Reference &amp; agent workflows — for later <span class="count">(' + reference.length + ")</span></h3>" +
        '<p class="calc-note">Not first-project skills: agent procedures, team methods, and briefs on models nobody can use yet. Kept for the record — see <code>SKILLS_AUDIT.md</code>.</p>' +
        '<div class="chapter-grid">' + reference.map(card).join("") + "</div>";
    }
    els.list.innerHTML = html;
    els.empty.hidden = shown.length > 0;
    els.count.textContent = shown.length + " of " + all.length + " skills";
  }

  fetch("skills-index.json")
    .then(function (r) { if (!r.ok) throw new Error("skills index failed"); return r.json(); })
    .then(function (idx) {
      all = idx.skills || [];
      render("");
      var deb;
      els.filter.addEventListener("input", function () {
        clearTimeout(deb);
        deb = setTimeout(function () { render(els.filter.value); }, 150);
      });
    })
    .catch(function () {
      els.list.innerHTML = '<div class="empty-state"><p>Could not load the skills index.</p></div>';
    });
})();
