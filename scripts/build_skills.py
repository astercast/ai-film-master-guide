#!/usr/bin/env python3
"""Generate the skills/ library for the AI Film Master Guide.

Usage: python3 scripts/build_skills.py
Reads data/v1/*.json, writes skills/<category>/<id>.md + skills/index.json.

Every skill is task-oriented (inputs, procedure, worked example, API refs,
pitfalls), generated from the guide's own verified data, never invented.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API = ROOT / "data" / "v1"
OUT = ROOT / "skills"
VERSION = "1.0.0"


def load(name):
    return json.loads((API / name).read_text())


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def article(word):
    return "an" if word[:1].lower() in "aeiou" else "a"


FILL_EXAMPLES = {
    "SUBJECT": "MARA", "ENV": "rain-slick alley", "LIGHT": "neon reflections",
    "STYLE": "1970s anamorphic 35mm, warm tungsten, halation, fine grain",
    "AUDIO": "wind, distant birds", "ACTION": "crosses the room",
    "MOVE": "slow dolly-in", "SHOT": "medium close-up",
}


def render(skill):
    """skill: dict(id, title, desc, gets, use, inputs, steps, example, apis,
    pitfalls[, audience]), `gets` is the rotation-20 plain-language
    'what this gets you' line: one short, concrete, outcome-first sentence
    a total beginner can judge the skill by in seconds (SKILLS_AUDIT.md)."""
    lines = [
        "---",
        f"name: {skill['id']}",
        f"description: {skill['desc']}",
        "---",
        "",
        f"# {skill['title']}",
        "",
    ]
    if skill.get("audience") == "reference":
        lines += ["> **Reference skill**, kept for the record, for agents, and for "
                  "later: not a first-project skill. See SKILLS_AUDIT.md (rotation 20).", ""]
    lines += [
        "## What this gets you",
        "",
        skill["gets"],
        "",
        "## Use when",
        "",
        skill["use"],
        "",
        "## Inputs",
        "",
    ]
    lines += [f"- {i}" for i in skill["inputs"]]
    lines += ["", "## Procedure", ""]
    lines += [f"{n}. {step}" for n, step in enumerate(skill["steps"], 1)]
    lines += ["", "## Worked example", "", skill["example"], ""]
    if skill.get("apis"):
        lines += ["## API references", ""]
        lines += [f"- `{a}`" for a in skill["apis"]]
        lines += [""]
    if skill.get("pitfalls"):
        lines += ["## Pitfalls", ""]
        lines += [f"- {p}" for p in skill["pitfalls"]]
        lines += [""]
    return "\n".join(lines)


def placeholders(prompt):
    return sorted(set(re.findall(r"\[([A-Z][A-Z /]+?)\]", prompt)))


# ---------------------------------------------------------------- data-driven

def prompt_skills(templates):
    out = []
    for t in templates["templates"]:
        ph = placeholders(t["prompt"])
        inputs = [f"`[{p}]`, {hint}" for p, hint in
                  [(p, {"SUBJECT": "locked identity label or @ reference",
                        "ENV": "environment description",
                        "LIGHT": "lighting direction",
                        "STYLE": "your style-bible line, verbatim",
                        "AUDIO": "sound direction (if model supports native audio)",
                        "ACTION": "single motion verb",
                        "MOVE": "camera movement",
                        "SHOT": "shot size"}.get(p, "fill per the template's anatomy"))
                   for p in ph]]
        filled = t["prompt"]
        for p in ph:
            if p in FILL_EXAMPLES:
                filled = filled.replace(f"[{p}]", FILL_EXAMPLES[p])
        out.append({
            "id": f"prompt-{t['id']}",
            "cat": "prompts",
            "title": f"Prompt: {t['title']}",
            "desc": f"Write {article(t['title'])} {t['title'].lower()} prompt ({t['track']} track) using the guide's template.",
            "gets": f"You will have a finished prompt for {article(t['title'])} {t['title'].lower()}"
                    + (f", the shot used for {t['use']}" if t.get("use") else "")
                    + ", ready to paste into a video model: fill the bracketed blanks, generate a cheap draft first, and keep the take that works.",
            "use": f"You are directing a shot that needs: {t['title'].lower()}. "
                   + (f"Anatomy: {t['anatomy']}." if t.get("anatomy") else "")
                   + (f" Best for: {t['use']}." if t.get("use") else ""),
            "inputs": inputs or ["No placeholders, use the template verbatim, then append your [STYLE] line."],
            "steps": [
                "Gather one value per placeholder. Keep [STYLE] identical to every other prompt in the project.",
                "Fill the template verbatim, do not paraphrase its camera language:",
                f"  `{t['prompt'][:220]}{'...' if len(t['prompt']) > 220 else ''}`",
                "Confirm exactly ONE primary motion and ONE camera move in the final prompt.",
                "Separate identity from motion: appearance descriptors in the Identity Block, action in the Motion Block, never pronouns alone as the subject anchor.",
                ("Add native-audio direction (quoted, attributed dialogue; named SFX) when the model supports it."
                 if t.get("models") and any("Veo" in m or "Seedance" in m or "Kling" in m for m in t["models"])
                 else "Handle audio in post (this template's models don't do native audio well)."),
                "Generate a 720p draft first; approve the select before any 1080p/4K render.",
            ],
            "example": f"Filled draft:\n`{filled[:400]}{'...' if len(filled) > 400 else ''}`",
            "apis": ["data/v1/prompt-templates.json", "data/v1/camera-movements.json"],
            "pitfalls": [
                "Stacking two motions or two camera moves in one prompt, the model will split the difference and ruin both.",
                "Changing the [STYLE] line between shots, the fastest route to a recast-looking cast.",
            ],
        })
    return out


