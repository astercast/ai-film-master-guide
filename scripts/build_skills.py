def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for f in OUT.rglob("*.md"):
        f.unlink()

    skills = []
    skills += prompt_skills(load("prompt-templates.json"))
    skills += camera_skills(load("camera-movements.json"))
    skills += model_skills(load("models.json"))
    skills += checklist_skills(load("checklists.json"))
    skills += build_hand_authored()

    index = []
    for s in skills:
        assert s.get("gets"), f"skill {s['id']} has no 'gets you' line (rotation-20 audit law)"
        s["audience"] = "reference" if s["id"] in REFERENCE_IDS else "beginner"
        cat_dir = OUT / s["cat"]
        cat_dir.mkdir(exist_ok=True)
        path = cat_dir / f"{s['id']}.md"
        path.write_text(render(s))
        index.append({"id": s["id"], "title": s["title"],
                      "description": s["desc"], "gets_you": s["gets"],
                      "audience": s["audience"],
                      "path": f"skills/{s['cat']}/{s['id']}.md"})

    (OUT / "index.json").write_text(json.dumps(
        {"version": VERSION, "count": len(index), "skills": index}, indent=2) + "\n")

    cats = {}
    for s in skills:
        cats[s["cat"]] = cats.get(s["cat"], 0) + 1
    print(f"film skills: {len(skills)}")
    for cat, n in sorted(cats.items()):
        print(f"  {cat}: {n}")


if __name__ == "__main__":
    main()
