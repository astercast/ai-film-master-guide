#!/usr/bin/env python3
"""Generate the skills/ library for the AI Film Master Guide.

Usage: python3 scripts/build_skills.py
Reads api/v1/*.json, writes skills/<category>/<id>.md + skills/index.json.

Every skill is task-oriented (inputs, procedure, worked example, API refs,
pitfalls) — generated from the guide's own verified data, never invented.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API = ROOT / "api" / "v1"
OUT = ROOT / "skills"
VERSION = "1.0.0"


def load(name):
    return json.loads((API / name).read_text())


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def article(word):
    return "an" if word[:1].lower() in "aeiou" else "a"


FILL_EXAMPLES = {
    "SUBJECT": "MARA", "ENV": "rain-slick alley", "LIGHT": "neon reflections",
    "STYLE": "1970s anamorphic 35mm, warm tungsten, halation, fine grain",
    "AUDIO": "wind, distant birds", "ACTION": "crosses the room",
    "MOVE": "slow dolly-in", "SHOT": "medium close-up",
}


def render(skill):
    """skill: dict(id, title, desc, use, inputs, steps, example, apis, pitfalls)"""
    lines = [
        "---",
        f"name: {skill['id']}",
        f"description: {skill['desc']}",
        "---",
        "",
        f"# {skill['title']}",
        "",
        "## Use when",
        "",
        skill["use"],
        "",
        "## Inputs",
        "",
    ]
    lines += [f"- {i}" for i in skill["inputs"]]
    lines += ["", "## Procedure", ""]
    lines += [f"{n}. {step}" for n, step in enumerate(skill["steps"], 1)]
    lines += ["", "## Worked example", "", skill["example"], ""]
    if skill.get("apis"):
        lines += ["## API references", ""]
        lines += [f"- `{a}`" for a in skill["apis"]]
        lines += [""]
    if skill.get("pitfalls"):
        lines += ["## Pitfalls", ""]
        lines += [f"- {p}" for p in skill["pitfalls"]]
        lines += [""]
    return "\n".join(lines)


def placeholders(prompt):
    return sorted(set(re.findall(r"\[([A-Z][A-Z /]+?)\]", prompt)))


# ---------------------------------------------------------------- data-driven

def prompt_skills(templates):
    out = []
    for t in templates["templates"]:
        ph = placeholders(t["prompt"])
        inputs = [f"`[{p}]` — {hint}" for p, hint in
                  [(p, {"SUBJECT": "locked identity label or @ reference",
                        "ENV": "environment description",
                        "LIGHT": "lighting direction",
                        "STYLE": "your style-bible line, verbatim",
                        "AUDIO": "sound direction (if model supports native audio)",
                        "ACTION": "single motion verb",
                        "MOVE": "camera movement",
                        "SHOT": "shot size"}.get(p, "fill per the template's anatomy"))
                   for p in ph]]
        filled = t["prompt"]
        for p in ph:
            if p in FILL_EXAMPLES:
                filled = filled.replace(f"[{p}]", FILL_EXAMPLES[p])
        out.append({
            "id": f"prompt-{t['id']}",
            "cat": "prompts",
            "title": f"Prompt: {t['title']}",
            "desc": f"Write {article(t['title'])} {t['title'].lower()} prompt ({t['track']} track) using the guide's template.",
            "use": f"You are directing a shot that needs: {t['title'].lower()}. "
                   + (f"Anatomy: {t['anatomy']}." if t.get("anatomy") else "")
                   + (f" Best for: {t['use']}." if t.get("use") else ""),
            "inputs": inputs or ["No placeholders — use the template verbatim, then append your [STYLE] line."],
            "steps": [
                "Gather one value per placeholder. Keep [STYLE] identical to every other prompt in the project.",
                "Fill the template verbatim — do not paraphrase its camera language:",
                f"  `{t['prompt'][:220]}{'...' if len(t['prompt']) > 220 else ''}`",
                "Confirm exactly ONE primary motion and ONE camera move in the final prompt.",
                "Separate identity from motion: appearance descriptors in the Identity Block, action in the Motion Block — never pronouns alone as the subject anchor.",
                ("Add native-audio direction (quoted, attributed dialogue; named SFX) when the model supports it."
                 if t.get("models") and any("Veo" in m or "Seedance" in m or "Kling" in m for m in t["models"])
                 else "Handle audio in post (this template's models don't do native audio well)."),
                "Generate a 720p draft first; approve the select before any 1080p/4K render.",
            ],
            "example": f"Filled draft:\n`{filled[:400]}{'...' if len(filled) > 400 else ''}`",
            "apis": ["api/v1/prompt-templates.json", "api/v1/camera-movements.json"],
            "pitfalls": [
                "Stacking two motions or two camera moves in one prompt — the model will split the difference and ruin both.",
                "Changing the [STYLE] line between shots — the fastest route to a recast-looking cast.",
            ],
        })
    return out


def camera_skills(moves):
    out = []
    for m in moves["movements"]:
        out.append({
            "id": f"camera-{m['id']}",
            "cat": "camera",
            "title": f"Direct: {m['move']}",
            "desc": f"Direct {article(m['move'])} {m['move'].lower()} camera move with exact prompt phrasing.",
            "use": f"Use when the shot needs what this move does: {m['when_to_use']}.",
            "inputs": [
                "Subject label or @ reference the move is motivated by",
                "Speed and stability (slow/majestic, energetic/handheld, locked)",
                "The story purpose of the move in one sentence",
            ],
            "steps": [
                f"Start from the guide's phrasing: `{m['prompt_phrasing'][:200]}{'...' if len(m['prompt_phrasing']) > 200 else ''}`",
                "State the move, the speed, AND the purpose — models obey motivated camera better than decorative camera.",
                "Keep it the only move in the prompt. One move per shot.",
                "Pair with a matching subject pace (tracking a runner = camera pace matches runner).",
                "Draft at 720p; check the move reads before committing to hero resolution.",
            ],
            "example": f"`{m['prompt_phrasing'][:300]}`",
            "apis": ["api/v1/camera-movements.json"],
            "pitfalls": [
                "Naming the move without speed/stability — 'dolly in' alone gives you a random dolly.",
                "Combining with a second move — pick one.",
            ],
        })
    return out


def model_skills(models):
    out = []
    for m in models["models"]:
        if m.get("status") == "discontinued":
            continue  # no "direct with" skill for dead models; history lives in model-watch
        mid = slug(m["model"])
        out.append({
            "id": f"direct-{mid}",
            "cat": "models",
            "title": f"Direct with {m['model']}",
            "desc": f"Use {m['model']} well: costs, strengths, weaknesses, best use.",
            "use": f"You are generating on {m['model']} ({m['platform']}, {m['type']}). Best use: {m['best_use']}.",
            "inputs": [
                f"Shot list with durations (cost basis: {m['est_cost_credits']})",
                "Whether you need native audio, lip sync, or long takes",
                "Your quality bar: draft (720p/fast) vs hero",
            ],
            "steps": [
                f"Budget first: {m['est_cost_credits']}. Multiply by 3–5× per hero shot for re-rolls.",
                f"Lean into its strength: {m['strength']}.",
                f"Design around its weakness — do not fight it: {m['weakness']}.",
                "Draft everything at the cheapest tier that still answers the creative question.",
                "Upscale or re-render at hero quality only for approved selects.",
            ],
            "example": f"10-second hero shot budgeting at {m['est_cost_credits']}: "
                       f"estimate the per-second rate, × 2 for duration, × 4 for re-roll headroom.",
            "apis": ["api/v1/models.json"],
            "pitfalls": [
                f"Weakness to respect: {m['weakness']}.",
                "Costs in models.json were refreshed 2026-10-11 — verify live before spending real money.",
            ],
        })
    return out


def checklist_skills(checklists):
    out = []
    for c in checklists["checklists"]:
        items = "\n".join(f"  - [ ] {it}" for it in c["items"][:8])
        out.append({
            "id": f"audit-{c['id']}",
            "cat": "checklists",
            "title": f"Run the {c['name']}",
            "desc": f"Run the guide's {c['name'].lower()} as a pass/fail audit.",
            "use": f"Run this audit at the matching production gate. Every item must pass before moving on.",
            "inputs": ["The current state of the production (script, prompts, selects, or cut)"],
            "steps": [
                "Go item by item. Mark pass/fail — no partial credit on hero shots.",
                "For each fail, write the concrete fix and who owns it.",
                "Re-run failed items only; don't redo the whole audit.",
                f"Key items:\n{items}",
            ],
            "example": "Per-shot audit on a dialogue close-up: one subject ✓, one action ✓, one camera move ✓, "
                       "identity/motion separated ✓, style bible appended ✓ → approved for 720p draft.",
            "apis": ["api/v1/checklists.json"],
            "pitfalls": ["Treating the audit as paperwork — its job is to catch the $500 mistake before you pay it."],
        })
    return out


