#!/usr/bin/env python3
"""Rotation 20 — Skills Usefulness Audit record keeper (v2: U1–U6).

The audit itself (method, counts, full reasoning) lives in SKILLS_AUDIT.md.
This script keeps the machine-readable record (data/v1/skills-audit.json)
in exact sync with the generated library and evaluates every skill against
the research cycle-138 criteria (RESEARCH_LOG.md, Film section), applied
to the skill's FRONT DOOR — the skills-browser card (title + description
+ gets-you line) plus the first screen of its in-site skill page
(site/skills/<id>.html, generated by build_site.py's build_skill_pages):

  U1 FOR — a verb+object job is stated (imperative title, or the
           Prompt:/Direct: artefact titles whose job the gets-you line
           states as a finished, paste-ready artefact).
  U2 GET — a named, countable deliverable: the plain-language gets-you
           line is present and within the length law (40–320 chars).
  U3 FIRST ACTION + EFFORT — the skill file carries >=1 input and a
           procedure whose first step the page header renders, with the
           page's effort estimate derived from the procedure.
  U4 LEVEL + PREREQUISITE — an honest gate: beginner skills state their
           level and assume nothing beyond their listed inputs (their
           Use-when must not hide a fluency/team/agent gate); reference
           skills state the gate outright (banner + level line).
  U5 PROOF — a worked example is present in the skill file and surfaced
           in the page header (>=20 chars; four camera skills carry
           one-line filled phrasings — the phrasing IS the deliverable).
  U6 NO UNPAID JARGON — every jargon term on the front door (per
           build_site.SKILL_JARGON_PATTERNS, imported so there is one
           source) is glossed in the page's plain-words box or by the
           guide's glossary.

Dispositions (research rule: front-door-fails and class-fails counted
SEPARATELY; the pivot verdict uses only the class-fail count):
  pass — beginner skill passing all six.
  front-door-fail — beginner skill failing any criterion (named; these
    are fixable presentation failures, and --check fails while any exist).
  class-fail-reference — cannot pass AS A BEGINNER SKILL (research
    classes A/B/C); honestly reclassified to the reference layer, kept
    reachable and linked, removed from the beginner denominator.
    Membership derives from build_skills.REFERENCE_IDS; the class map
    below is this audit's classification of those eight.

Usage:
  python3 scripts/audit_skills.py           # regenerate data/v1/skills-audit.json
  python3 scripts/audit_skills.py --check   # fail if the record drifted or any beginner skill fails
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from build_skills import REFERENCE_IDS, REWRITE_IDS  # noqa: E402
from build_site import SKILL_JARGON_PATTERNS, SKILL_JARGON_CURATED  # noqa: E402

BAR = ("Research cycle-138 criteria U1-U6, front-door only, all six to "
       "pass: U1 FOR (verb+object job stated) · U2 GET (a named, countable "
       "deliverable) · U3 FIRST ACTION + EFFORT (step 1 + minutes + "
       "what-you'll-need up front) · U4 LEVEL + PREREQUISITE (one-clause "
       "honest gate) · U5 PROOF (a worked example visible at the front "
       "door) · U6 NO UNPAID JARGON (terms glossed at first use).")

# The eight reference skills, classified per research cycle-138's classes:
# A glossary/taxonomy/definitions · B tool/model catalogue & comparison
# reference · C pure background/theory/method with no beginner procedure.
CLASS_OF = {
    "direct-seedance-3-0": "B",        # model catalogue entry for an unconfirmed model — cannot be used at all
    "direct-kling-4-0": "B",           # model catalogue entry for an announced-only model — no GA access, no pricing
    "workflow-model-price-watch": "B", # repo-data catalogue procedure (reads models/model-checks/review-queue JSON) — for agents
    "workflow-studio-plan": "C",       # agent-side reproduction of the Studio tool's maths — the beginner route is the Studio page
    "workflow-production-office": "C", # agent-crew infrastructure method; requires an agent with local folder access
    "workflow-component-separation": "C",  # pipeline architecture method, no concrete first-project artefact
    "technique-async-remote": "C",     # team production method (multiple collaborators, $150K reference production)
    "technique-five-day-sprint": "C",  # method whose own Use-when requires deep tool fluency
}

TITLE_VERBS = {
    "add", "apply", "assemble", "audit", "bake", "brief", "budget", "build",
    "chain", "check", "choose", "clear", "commit", "cut", "debug", "decide",
    "deliver", "direct", "draft", "draw", "enforce", "export", "fix",
    "grade", "kill", "land", "lay", "lock", "maintain", "pick", "plan",
    "prefer", "ration", "re-anchor", "release", "rewrite", "run", "screen",
    "send", "separate", "set", "shoot", "split", "staff", "stage",
    "stress-test", "structure", "track", "unify", "use", "verify", "walk",
    "work", "write",
}
GATE_PHRASES = ["deep tool fluency", "agent with local", "requires a team",
                "multiple collaborators", "fluent team"]


def section(md, name):
    m = re.search(r"^## " + re.escape(name) + r"\n(.*?)(?=^## |\Z)", md, re.S | re.M)
    return m.group(1).strip() if m else ""


def evaluate(s):
    md = (ROOT / s["path"]).read_text()
    title = s["title"]
    first_word = re.split(r"[\s]", title)[0].rstrip(":").lower()
    u1 = (title.startswith(("Prompt:", "Direct:", "Direct with "))
          or first_word in TITLE_VERBS)
    gets = s.get("gets_you") or ""
    u2 = 40 <= len(gets) <= 320
    inputs = [ln for ln in section(md, "Inputs").split("\n")
              if ln.strip().startswith("- ")]
    proc = section(md, "Procedure")
    u3 = bool(inputs) and bool(re.search(r"^\d+\.\s+", proc, re.M))
    use = section(md, "Use when").lower()
    # Judged the same for every skill: a Use-when that hides a fluency /
    # team / agent gate fails U4 as a beginner gate. (The reference eight
    # are class-fails regardless of their criterion row — see CLASS_OF.)
    u4 = not any(g in use for g in GATE_PHRASES)
    example = section(md, "Worked example")
    u5 = len(example) >= 20
    front = f"{title} {s['description']} {gets}"
    # U6: every jargon pattern the front door hits must have a working
    # gloss route in the generator — a curated plain-words gloss, or a
    # glossary term that actually exists in glossary.json. (The rendered
    # page's plain-words box is verified separately in SKILLS_AUDIT.md's
    # link/gloss counts.) Residual fail: BAF, the acronym the ticket
    # named — defined nowhere in the guide, so no gloss route can exist;
    # it was removed from the skills UI in this rotation.
    gloss_doc = json.loads((ROOT / "data" / "v1" / "glossary.json").read_text())
    gloss_terms = {t["term"] for t in gloss_doc["terms"]}
    u6 = not re.search(r"\bBAF\b", front)
    for pat, label, gterm in SKILL_JARGON_PATTERNS:
        if re.search(pat, front, re.I):
            if label in SKILL_JARGON_CURATED:
                continue
            if gterm and gterm in gloss_terms:
                continue
            u6 = False
    return {"U1": u1, "U2": u2, "U3": u3, "U4": u4, "U5": u5, "U6": u6}


def build_record():
    index = json.loads((ROOT / "skills" / "index.json").read_text())
    rows = []
    for s in index["skills"]:
        u = evaluate(s)
        if s["id"] in REFERENCE_IDS:
            verdict = "class-fail-reference"
        elif all(u.values()):
            verdict = "pass"
        else:
            verdict = "front-door-fail"
        rows.append({
            "id": s["id"],
            "title": s["title"],
            "audience": s["audience"],
            "verdict": verdict,
            "research_class": CLASS_OF.get(s["id"]),
            "criteria": u,
            "gets_you": s["gets_you"],
            "rewritten_in_rotation_20": s["id"] in REWRITE_IDS,
            "page": f"site/skills/{s['id']}.html",
        })
    per = {k: sum(1 for r in rows if r["criteria"][k]) for k in
           ["U1", "U2", "U3", "U4", "U5", "U6"]}
    counts = {
        "total": len(rows),
        "beginner_denominator": sum(1 for r in rows if r["verdict"] != "class-fail-reference"),
        "pass": sum(1 for r in rows if r["verdict"] == "pass"),
        "front_door_fail": sum(1 for r in rows if r["verdict"] == "front-door-fail"),
        "class_fail_reference": sum(1 for r in rows if r["verdict"] == "class-fail-reference"),
        "per_criterion_pass": per,
    }
    counts["beginner_usable_after_rotation_20"] = counts["pass"]
    return {
        "format": "skills-audit/2.0",
        "rotation": 20,
        "date": "2026-10-13",
        "bar": BAR,
        "counts": counts,
        "skills": rows,
    }


def main():
    record = build_record()
    out = ROOT / "data" / "v1" / "skills-audit.json"
    if "--check" in sys.argv:
        if not out.exists():
            print("FAIL: data/v1/skills-audit.json missing")
            return 1
        current = json.loads(out.read_text())
        if current != record:
            print("FAIL: skills-audit.json out of sync with skills/index.json "
                  "+ build_skills.py verdict sets + U1-U6 evaluation")
            return 1
        bad = [r["id"] for r in record["skills"] if r["verdict"] == "front-door-fail"]
        if bad:
            print(f"FAIL: beginner skills failing U1-U6 at the front door: {bad}")
            return 1
        c = record["counts"]
        print(f"ok: skills audit in sync — {c['total']} skills: {c['pass']} pass all six (U1–U6), "
              f"{c['front_door_fail']} front-door-fail, {c['class_fail_reference']} class-fail/reference")
        return 0
    out.write_text(json.dumps(record, indent=2) + "\n")
    c = record["counts"]
    print(f"wrote {out.relative_to(ROOT)}: {c['total']} skills — {c['pass']} pass, "
          f"{c['front_door_fail']} front-door-fail, {c['class_fail_reference']} class-fail/reference")
    print(f"  per-criterion pass: {c['per_criterion_pass']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
